"""Generate fixture DTOs from the reviewed JSON schema; never hand-edit outputs."""

import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PROTOCOL = ROOT / "Mtg_Projects/mtg_play/protocol"


def check_fixture_schema_subset(rule):
    """Fail when the schema gains a keyword not covered by both test consumers."""
    if isinstance(rule, bool):
        return
    supported = {
        "$schema",
        "$id",
        "title",
        "$defs",
        "$ref",
        "type",
        "properties",
        "required",
        "additionalProperties",
        "anyOf",
        "allOf",
        "if",
        "then",
        "enum",
        "const",
        "minimum",
        "items",
        "prefixItems",
        "minItems",
        "maxItems",
    }
    if set(rule) - supported:
        raise ValueError(
            f"Unsupported fixture schema keywords: {sorted(set(rule) - supported)}"
        )
    for name in ("properties", "$defs"):
        for child in rule.get(name, {}).values():
            check_fixture_schema_subset(child)
    for name in ("anyOf", "allOf", "prefixItems"):
        for child in rule.get(name, []):
            check_fixture_schema_subset(child)
    for name in ("items", "if", "then"):
        if name in rule:
            check_fixture_schema_subset(rule[name])


def field_type(shape, language):
    if "$ref" in shape:
        return shape["$ref"].rsplit("/", 1)[1]
    if "anyOf" in shape:
        alternatives = [part for part in shape["anyOf"] if part.get("type") != "null"]
        if len(alternatives) != 1:
            raise ValueError("Only nullable unions are supported")
        value = field_type(alternatives[0], language)
        return value + "?" if language == "cs" and value in ("long", "bool") else value
    if "enum" in shape:
        if not all(isinstance(item, str) for item in shape["enum"]):
            raise ValueError("Unsupported enum")
        return "string" if language == "cs" else "String"
    if "const" in shape:
        return "long" if language == "cs" else "Long"
    kind = shape["type"]
    if kind == "array":
        item = (
            field_type(shape["items"], language)
            if "prefixItems" not in shape
            else ("JToken" if language == "cs" else "JsonElement")
        )
        return item + "[]"
    return {
        "string": ("string", "String"),
        "integer": ("long", "Long"),
        "boolean": ("bool", "Boolean"),
    }[kind][language == "java"]


def outputs():
    raw = (PROTOCOL / "python-contracts-v1.schema.json").read_text(encoding="utf-8")
    schema = json.loads(raw)
    check_fixture_schema_subset(schema)
    digest = hashlib.sha256(raw.encode()).hexdigest()
    header = f"// Generated by tools/generate_play_models.py; schema SHA-256 (UTF-8/LF): {digest}\n"
    cs = [
        header,
        "using Newtonsoft.Json;\nusing Newtonsoft.Json.Linq;\n\nnamespace Manaforge.Play.Protocol\n{\n",
    ]
    java = [
        header,
        "package manaforge.protocol;\n\nimport com.google.gson.JsonElement;\nimport com.google.gson.annotations.SerializedName;\n\npublic final class PlayContracts {\n    private PlayContracts() {}\n",
    ]
    for name, definition in schema["$defs"].items():
        cs.append(f"    public sealed class {name}\n    {{\n")
        java.append(f"    public static final class {name} {{\n")
        for field, shape in definition["properties"].items():
            cs_name = "@default" if field == "default" else field
            java_name = "defaultValue" if field == "default" else field
            nullable = any(
                part.get("type") == "null" for part in shape.get("anyOf", [])
            )
            required = "AllowNull" if nullable else "Always"
            cs.append(
                f'        [JsonProperty("{field}", Required = Required.{required})]\n        public {field_type(shape, "cs")} {cs_name};\n'
            )
            java.append(
                f'        @SerializedName("{field}")\n        public {field_type(shape, "java")} {java_name};\n'
            )
        cs.append("    }\n")
        java.append("    }\n")
    cs.append("}\n")
    java.append("}\n")
    return {
        ROOT
        / "Mtg_Projects/mtg_play_unity/Assets/Manaforge/Runtime/Protocol/PlayContracts.cs": "".join(
            cs
        ),
        PROTOCOL / "java/manaforge/protocol/PlayContracts.java": "".join(java),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for path, expected in outputs().items():
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != expected:
                parser.exit(1, f"Generated model drift: {path.name}\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected, encoding="utf-8")
    print(
        "Generated Java/C# fixture DTOs match schema."
        if args.check
        else "Generated Java/C# fixture DTOs."
    )


if __name__ == "__main__":
    main()
